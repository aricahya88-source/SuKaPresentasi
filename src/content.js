export function parseRoute(hash) {
  const match = /^#\/presentasi\/([a-z0-9-]+)\/(\d+)$/.exec(hash);
  if (!match) return null;
  const id = match[1] === "fisika" ? "pendidikan-fisika" : match[1];
  const deck = decks.find((d) => d.id === id);
  return deck
    ? {
        deck,
        index: Math.max(
          0,
          Math.min(deck.slides.length - 1, Number(match[2]) - 1),
        ),
      }
    : null;
}
